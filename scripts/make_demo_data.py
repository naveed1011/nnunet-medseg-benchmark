"""
Generate a small, fully synthetic dataset in nnU-Net v2 format.

Why this exists
---------------
Downloading MSD/BraTS and training nnU-Net just to check that *the plumbing*
works costs gigabytes and GPU-hours. This script writes a tiny phantom dataset
with the same folder contract as a real task — multiple modalities, three
foreground labels, anisotropic spacing — so you can:

  * run the complete nnU-Net pipeline end-to-end on CPU in minutes,
  * exercise `src/metrics.py`, `src/xai.py` and `src/compare.py` on real files,
  * run the test suite / CI without any data download.

It is **not** medical data and the Dice numbers it produces say nothing about
real segmentation quality. That is the point: it is a smoke test.

Usage
-----
    python scripts/make_demo_data.py --out nnUNet_raw --n-cases 12
    python scripts/make_demo_data.py --qc-figure docs/figures/demo_data_qc.png
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))


def _sphere(z, y, x, center, radius):
    """Sphere in mm, with z/y/x matching axes 0/1/2."""
    return ((z - center[0]) ** 2 + (y - center[1]) ** 2 + (x - center[2]) ** 2) <= radius ** 2


def make_case(shape, spacing, rng, index: int):
    """Return (image [2, D, H, W] float32 in ~MRI units, label [D, H, W] uint8)."""
    d, h, w = shape
    # coordinates in mm, one array per axis so anisotropic spacing is handled right
    zz, yy, xx = np.mgrid[0:d, 0:h, 0:w]
    z = zz * spacing[0]
    y = yy * spacing[1]
    x = xx * spacing[2]

    half = np.array([d * spacing[0], h * spacing[1], w * spacing[2]]) / 2.0
    # slightly jittered head-like ellipsoid
    brain = ((z - half[0]) / (half[0] * 0.86)) ** 2 + \
            ((y - half[1]) / (half[1] * 0.90)) ** 2 + \
            ((x - half[2]) / (half[2] * 0.92)) ** 2 <= 1.0

    # tumour: core + edema shell + a small enhancing blob inside the core
    r_core = rng.uniform(6.0, 9.0)
    r_edema = r_core + rng.uniform(3.0, 5.5)
    r_blob = rng.uniform(2.5, 4.0)
    centre = half + rng.uniform(-0.12, 0.12, 3) * half
    blob_centre = centre + rng.uniform(-0.45, 0.45, 3) * r_core

    core = _sphere(z, y, x, centre, r_core) & brain
    edema = _sphere(z, y, x, centre, r_edema) & brain & ~core
    blob = _sphere(z, y, x, blob_centre, r_blob) & core
    if not blob.any():          # keep every class present
        blob = core & _sphere(z, y, x, centre, 1.5)

    labels = np.zeros(shape, dtype=np.uint8)
    labels[edema] = 2
    labels[core] = 1
    labels[blob] = 3

    # smooth tissue texture (low-frequency noise), then a multiplicative bias field
    from scipy.ndimage import gaussian_filter
    texture = gaussian_filter(rng.normal(0, 1, shape).astype(np.float32), sigma=3.0)
    texture = (texture - texture.min()) / (texture.max() - texture.min() + 1e-8)
    bias = gaussian_filter(rng.normal(0, 1, shape).astype(np.float32), sigma=12.0)
    bias = 1.0 + 0.25 * bias / (np.abs(bias).max() + 1e-8)

    t1 = 0.35 * brain + 0.25 * texture * brain
    t2 = 0.30 * brain + 0.20 * texture * brain
    t1 = t1 + 0.55 * core + 0.15 * edema + 0.90 * blob
    t2 = t2 + 0.20 * core + 0.65 * edema + 0.30 * blob
    t1 = 0.5 + (t1 + rng.normal(0, 0.02, shape)) * bias
    t2 = 0.5 + (t2 + rng.normal(0, 0.02, shape)) * bias
    # MRI-like scale (arbitrary units); outside the head stays exactly 0
    image = np.stack([t1, t2]).astype(np.float32) * 1000.0 * brain
    return image, labels


def _write_dataset(out_root: Path, n_cases: int, shape, spacing, n_val: int,
                   seed: int, force: bool) -> Path:
    import nibabel as nib

    ds_dir = out_root / "Dataset900_Phantom"
    if ds_dir.exists():
        if not force:
            raise SystemExit(f"{ds_dir} already exists — pass --force to regenerate it")
        shutil.rmtree(ds_dir)
    (ds_dir / "imagesTr").mkdir(parents=True)
    (ds_dir / "labelsTr").mkdir(parents=True)

    rng = np.random.default_rng(seed)
    affine = np.diag([spacing[0], spacing[1], spacing[2], 1.0])
    cases = []
    for i in range(n_cases):
        image, labels = make_case(shape, spacing, rng, i)
        cid = f"phantom_{i:03d}"
        cases.append(cid)
        for ch in range(image.shape[0]):
            nib.save(nib.Nifti1Image(image[ch], affine),
                     str(ds_dir / "imagesTr" / f"{cid}_{ch:04d}.nii.gz"))
        nib.save(nib.Nifti1Image(labels, affine), str(ds_dir / "labelsTr" / f"{cid}.nii.gz"))

    dataset_json = {
        "name": "Dataset900_Phantom",
        "description": "Synthetic 2-modality, 3-label phantom for pipeline smoke tests (NOT medical data)",
        "reference": "generated by scripts/make_demo_data.py",
        "licence": "CC0-1.0",
        "release": "1.0",
        "numTraining": len(cases),
        "file_ending": ".nii.gz",
        "channel_names": {"0": "T1-like", "1": "T2-like"},
        "labels": {
            "background": 0,
            "core": 1,
            "edema": 2,
            "enhancing": 3,
        },
    }
    (ds_dir / "dataset.json").write_text(json.dumps(dataset_json, indent=4) + "\n", encoding="utf-8")

    # fixed, documented split (deterministic: every k-th case is validation)
    n_val = max(1, min(n_val, len(cases) - 1))
    stride = max(1, len(cases) // n_val)
    val = [c for i, c in enumerate(cases) if i % stride == stride - 1][:n_val]
    train = [c for c in cases if c not in val]
    split = {"dataset": "Dataset900_Phantom", "fold": 0,
             "seed": seed, "train": train, "val": val}
    (ds_dir / "demo_split.json").write_text(json.dumps(split, indent=2) + "\n", encoding="utf-8")

    print(f"✅ Dataset900_Phantom: {len(cases)} cases, 2 channels, labels 1/2/3")
    print(f"   {ds_dir}")
    print(f"   split: {len(train)} train / {len(val)} val -> demo_split.json")
    return ds_dir


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out", default=None,
                   help="nnUNet_raw root (default: $nnUNet_raw or ./nnUNet_raw)")
    p.add_argument("--n-cases", type=int, default=12)
    p.add_argument("--shape", type=int, nargs=3, default=(72, 72, 56),
                   help="volume shape in voxels (default 72 72 56)")
    p.add_argument("--spacing", type=float, nargs=3, default=(1.0, 1.0, 1.5),
                   help="voxel spacing in mm (default 1.0 1.0 1.5, deliberately anisotropic)")
    p.add_argument("--n-val", type=int, default=3)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--force", action="store_true", help="overwrite an existing Dataset900_Phantom")
    p.add_argument("--qc-figure", default=None,
                   help="write a dataset QC PNG (e.g. docs/figures/demo_data_qc.png)")
    args = p.parse_args()

    import os
    out_root = Path(args.out) if args.out else Path(os.environ.get("nnUNet_raw", "nnUNet_raw"))
    ds_dir = _write_dataset(out_root, args.n_cases, tuple(args.shape),
                            tuple(args.spacing), args.n_val, args.seed, args.force)

    if args.qc_figure:
        import nibabel as nib
        from src.figures import plot_dataset_qc

        ids = sorted(p.name[: -len("_0000.nii.gz")]
                     for p in (ds_dir / "imagesTr").glob("*_0000.nii.gz"))
        picks = ids[:4]
        images = [np.asarray(nib.load(str(ds_dir / "imagesTr" / f"{c}_0000.nii.gz")).dataobj)
                  for c in picks]
        labels = [np.asarray(nib.load(str(ds_dir / "labelsTr" / f"{c}.nii.gz")).dataobj)
                  for c in picks]
        plot_dataset_qc(images, labels, args.qc_figure, titles=picks)


if __name__ == "__main__":
    main()
